"""
SLURM integration for MCCE4 GUI.

Generates sbatch scripts, submits jobs, and polls job status via squeue.
"""

from __future__ import annotations

import asyncio
import os
import re
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

from .config import MCCEConfig, SlurmConfig


@dataclass
class SlurmJobInfo:
    """Status of a submitted SLURM job."""
    job_id: str = ""
    state: str = "UNKNOWN"      # PENDING, RUNNING, COMPLETED, FAILED, CANCELLED, TIMEOUT
    elapsed: str = ""
    node: str = ""
    exit_code: str = ""

    def to_dict(self) -> dict:
        return {
            "job_id": self.job_id,
            "state": self.state,
            "elapsed": self.elapsed,
            "node": self.node,
            "exit_code": self.exit_code,
        }


def is_slurm_available() -> bool:
    """Check if SLURM commands are available on this system."""
    return shutil.which("sbatch") is not None


def generate_sbatch_script(config: MCCEConfig) -> str:
    """Generate an sbatch script from the MCCE4 config."""
    slurm = config.slurm
    mcce_home = config.mcce_home
    diel = str(config.inner_dielectric)

    lines = [
        "#!/bin/bash",
        f"#SBATCH --job-name={slurm.job_name}",
        f"#SBATCH --cpus-per-task={slurm.cpus}",
        f"#SBATCH --mem={slurm.memory_gb}G",
        f"#SBATCH --time={slurm.time_limit}",
        f"#SBATCH --output=mcce4_%j.out",
        f"#SBATCH --error=mcce4_%j.err",
    ]

    if slurm.partition:
        lines.append(f"#SBATCH --partition={slurm.partition}")

    if slurm.extra_directives:
        for directive in slurm.extra_directives.strip().split("\n"):
            directive = directive.strip()
            if directive:
                lines.append(f"#SBATCH {directive}")

    lines.extend([
        "",
        f"# Generated by mcce4_gui",
        f"# Working directory: {os.getcwd()}",
        "",
        f'export MCCE_HOME="{mcce_home}"',
        "",
        "set -euo pipefail",
        "echo \"Job started: $(date)\"",
        "echo \"Node: $(hostname)\"",
        "echo \"Working directory: $(pwd)\"",
        "",
    ])

    # Build param_env
    param_env = f"-u MCCE_HOME={mcce_home}"
    if config.extra_tpl:
        param_env += f",EXTRA={config.extra_tpl}"

    # Add step commands
    if config.step1.enabled:
        cmd = f'python "{mcce_home}/bin/step1.py" "{config.pdb_file}" -d {diel}'
        if config.step1.dry:
            cmd += " --dry"
        cmd += f" {param_env}"
        lines.extend([
            "echo '── Step 1: Preparation ──'",
            f"time {cmd}",
            "echo 'Step 1 complete'",
            "",
        ])

    if config.step2.enabled:
        cmd = (
            f'python "{mcce_home}/bin/step2.py"'
            f" -l {config.step2.conformer_level} -d {diel} {param_env}"
        )
        lines.extend([
            "echo '── Step 2: Rotamers ──'",
            f"time {cmd}",
            "echo 'Step 2 complete'",
            "",
        ])

    if config.step3.enabled:
        cmd = (
            f'python "{mcce_home}/bin/step3.py"'
            f" -d {diel}"
            f" -do {config.outer_dielectric}"
            f" -p {config.step3.processes}"
            f" -salt {config.step3.salt}"
        )
        solver = config.step3.pbe_solver
        if solver != "ngpb":
            cmd += f" --solver {solver}"
        for flag in ["skip_pb", "old_vdw", "fly", "refresh", "debug"]:
            if getattr(config.step3, flag, False):
                cmd += f" --{flag.replace('_', '-')}"
        cmd += f" {param_env}"
        lines.extend([
            "echo '── Step 3: Energies ──'",
            f"time {cmd}",
            "echo 'Step 3 complete'",
            "",
        ])

    if config.step4.enabled:
        cmd = (
            f'python "{mcce_home}/bin/step4.py"'
            f" -i {config.step4.init_ph}"
            f" -d {config.step4.interval}"
            f" -n {config.step4.titration_steps}"
            f" -t {config.step4.titration_type}"
        )
        if config.step4.xts:
            cmd += " --xts"
        if config.step4.ms:
            cmd += " --ms"
        cmd += f" {param_env}"
        lines.extend([
            "echo '── Step 4: Monte Carlo ──'",
            f"time {cmd}",
            "echo 'Step 4 complete'",
            "",
        ])

    lines.extend([
        'echo "Job finished: $(date)"',
    ])

    return "\n".join(lines) + "\n"


async def submit_job(config: MCCEConfig) -> str:
    """
    Submit an sbatch job. Returns the job ID.
    Raises RuntimeError on failure.
    """
    if not is_slurm_available():
        raise RuntimeError("SLURM is not available on this system (sbatch not found)")

    script = generate_sbatch_script(config)

    # Write script to file
    script_path = Path("mcce4_slurm.sh")
    script_path.write_text(script)
    script_path.chmod(0o755)

    proc = await asyncio.create_subprocess_exec(
        "sbatch", str(script_path),
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    stdout, stderr = await proc.communicate()

    if proc.returncode != 0:
        err = stderr.decode().strip()
        raise RuntimeError(f"sbatch failed: {err}")

    output = stdout.decode().strip()
    # Parse "Submitted batch job 12345"
    match = re.search(r"(\d+)", output)
    if not match:
        raise RuntimeError(f"Could not parse job ID from: {output}")

    return match.group(1)


async def get_job_status(job_id: str) -> SlurmJobInfo:
    """Query SLURM for job status using sacct (or squeue as fallback)."""
    info = SlurmJobInfo(job_id=job_id)

    if not is_slurm_available():
        info.state = "UNKNOWN"
        return info

    # Try sacct first (works for completed jobs too)
    try:
        proc = await asyncio.create_subprocess_exec(
            "sacct", "-j", job_id,
            "--format=JobID,State,Elapsed,NodeList,ExitCode",
            "--noheader", "--parsable2",
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        stdout, _ = await proc.communicate()

        if proc.returncode == 0:
            for line in stdout.decode().strip().split("\n"):
                parts = line.split("|")
                if len(parts) >= 5 and parts[0] == job_id:
                    info.state = parts[1].strip()
                    info.elapsed = parts[2].strip()
                    info.node = parts[3].strip()
                    info.exit_code = parts[4].strip()
                    return info
    except FileNotFoundError:
        pass

    # Fallback: squeue for running/pending jobs
    try:
        proc = await asyncio.create_subprocess_exec(
            "squeue", "-j", job_id,
            "--format=%i|%T|%M|%N",
            "--noheader",
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        stdout, _ = await proc.communicate()

        if proc.returncode == 0 and stdout.strip():
            parts = stdout.decode().strip().split("|")
            if len(parts) >= 4:
                info.state = parts[1].strip()
                info.elapsed = parts[2].strip()
                info.node = parts[3].strip()
        else:
            # Job not in queue — likely completed
            info.state = "COMPLETED"
    except FileNotFoundError:
        info.state = "UNKNOWN"

    return info


async def cancel_job(job_id: str) -> bool:
    """Cancel a SLURM job. Returns True on success."""
    if not is_slurm_available():
        return False

    proc = await asyncio.create_subprocess_exec(
        "scancel", job_id,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    await proc.communicate()
    return proc.returncode == 0
